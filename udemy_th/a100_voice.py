"""Remote GPU Voice & ASR client for Colab A100 (`colab/hongrian_voice_a100.ipynb`).

Runs heavy speech synthesis, zero-shot voice cloning, T2ST, and Whisper ASR on a
rented A100 GPU over a Cloudflare tunnel while keeping `agy` local for subtitle
translation.

Configuration in `.env`:
    UDTH_A100_URL       Tunnel URL printed by the Colab A100 notebook
    UDTH_A100_KEY       Bearer API key generated by the notebook
    UDTH_A100_PARALLEL  Parallel synthesis workers for lecture prefetch (default 6)
    UDTH_VOICE_REF      5-10s instructor audio sample for zero-shot cloning
    UDTH_VOICE_REF_TEXT Optional transcript of UDTH_VOICE_REF

Resilience (Circuit Breaker):
    When the Colab runtime disconnects or the tunnel expires, `A100Unavailable`
    trips a 60-second cooldown so subsequent sentences fall back immediately to
    the local GPU or Microsoft Edge Neural TTS without waiting out a timeout on
    every line. Wrong API keys (401/403) raise `TtsError` immediately.
"""

from __future__ import annotations

import base64
import contextlib
import contextvars
import hashlib
import heapq
import itertools
import json
import os
import threading
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from pathlib import Path

from .google_tts import TtsError

TIMEOUT_SECONDS = 90.0
# Ask the A100 for compressed audio. The free tunnel carried ~75 KB/s: a 5.5s
# line as WAV (265 KB, 353 KB in base64) took 3s to arrive after 1.45s of
# work; as Ogg Vorbis it is ~35 KB. Kept as WAV in the local cache, so nothing
# downstream changes. Needs soundfile here to decode; without it, plain WAV.
COMPRESSED_FORMAT = "ogg"
RETRY_AFTER_SECONDS = 60.0
PREFETCH_PARALLEL = max(1, int(os.environ.get("UDTH_A100_PARALLEL", "6")))


class A100Unavailable(RuntimeError):
    """The remote A100 voice server could not be reached."""


# Who is waiting for a clip. The GPU on the other end makes one at a time and
# serves concurrent requests in no particular order: measured on Udemy, the
# line due now came back after the four the player asked for ahead of it
# (5.5s instead of 1.9s). So this server sends one request at a time, in
# this order, instead of leaving the order to chance.
NOW, AHEAD, BACKGROUND = 0, 1, 2
priority: contextvars.ContextVar[int] = contextvars.ContextVar("udth_a100_priority", default=AHEAD)


class _PriorityGate:
    """One holder at a time; the lowest priority number goes next, then FIFO."""

    def __init__(self):
        self._cond = threading.Condition()
        self._busy = False
        self._waiting: list[tuple[int, int]] = []
        self._order = itertools.count()

    @contextlib.contextmanager
    def turn(self, level: int):
        with self._cond:
            ticket = (level, next(self._order))
            heapq.heappush(self._waiting, ticket)
            while self._busy or self._waiting[0] != ticket:
                self._cond.wait()
            heapq.heappop(self._waiting)
            self._busy = True
        try:
            yield
        finally:
            with self._cond:
                self._busy = False
                self._cond.notify_all()


_gate = _PriorityGate()


_state_lock = threading.Lock()
_down_until: float = 0.0
_uploaded_refs: set[tuple[str, str]] = set()

# The Colab tunnel gets a new URL every run. Read these two from .env again
# when the file changes, so pasting the new values is enough and the server
# does not need a restart. A value set in the real environment still wins.
_LIVE_NAMES = ("UDTH_A100_URL", "UDTH_A100_KEY")
_dotenv = {"mtime": None, "checked": -1e9}


def _follow_dotenv(now: Callable[[], float] = time.monotonic) -> None:
    from . import env

    if os.environ.get("UDTH_NO_DOTENV"):
        return
    with _state_lock:
        if now() - _dotenv["checked"] < 2.0:
            return
        _dotenv["checked"] = now()
    try:
        mtime = env.ENV_PATH.stat().st_mtime
        if mtime == _dotenv["mtime"]:
            return
        values = env.parse(env.ENV_PATH.read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeDecodeError):
        return
    _dotenv["mtime"] = mtime
    changed = False
    for name in _LIVE_NAMES:
        from_file = name in env.LOADED or not os.environ.get(name)
        if not from_file:
            continue  # set by the real environment: leave it alone
        new = values.get(name, "")
        if (os.environ.get(name) or "") != new:
            changed = True
            if new:
                os.environ[name] = new
                if name not in env.LOADED:
                    env.LOADED.append(name)
            else:
                os.environ.pop(name, None)
    if changed:
        reset_circuit()  # a new server: try it at once, and it has none of our references


def configured() -> bool:
    _follow_dotenv()
    return bool((os.environ.get("UDTH_A100_URL") or "").strip())


def base_url(url: str | None = None) -> str:
    if url is None:
        _follow_dotenv()
    raw = (url if url is not None else os.environ.get("UDTH_A100_URL", "")).strip().rstrip("/")
    if raw.endswith("/v1"):
        raw = raw[:-3].rstrip("/")
    return raw


def api_key(key: str | None = None) -> str:
    return (key if key is not None else os.environ.get("UDTH_A100_KEY", "")).strip()


def describe() -> str:
    url = base_url()
    return f"A100 Voice Server ที่ {url}" if url else "ไม่ได้ตั้งค่า A100"


def reference_path(override: str | None = None) -> Path | None:
    raw = override or os.environ.get("UDTH_VOICE_REF") or os.environ.get("UDTH_OMNIVOICE_REF") or ""
    raw = raw.strip()
    return Path(raw) if raw else None


def reference_text(override: str | None = None) -> str | None:
    raw = override or os.environ.get("UDTH_VOICE_REF_TEXT") or os.environ.get("UDTH_OMNIVOICE_REF_TEXT") or ""
    raw = raw.strip()
    return raw or None


def reference_identity(path: Path, text: str | None = None) -> str:
    stat = path.stat()
    raw = f"{path.resolve()}\0{stat.st_size}\0{int(stat.st_mtime)}\0{text or ''}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:24]


def reset_circuit() -> None:
    """Clear cooldown and uploaded-ref state (used by tests and manual reload)."""
    global _down_until
    with _state_lock:
        _down_until = 0.0
        _uploaded_refs.clear()


def is_available(now: Callable[[], float] = time.monotonic) -> bool:
    if not configured():
        return False
    with _state_lock:
        return now() >= _down_until


def mark_down(reason: str, now: Callable[[], float] = time.monotonic, log=print) -> None:
    global _down_until
    with _state_lock:
        _down_until = now() + RETRY_AFTER_SECONDS
    log(
        f"  [A100] {reason} — สลับไปใช้เสียงสำรองในเครื่องแทน "
        f"(จะลอง A100 ใหม่ใน {int(RETRY_AFTER_SECONDS)} วินาที)",
        flush=True,
    )


def _can_decode_compressed() -> bool:
    try:
        import soundfile

        return "OGG" in soundfile.available_formats()
    except Exception:
        return False


def _to_wav(audio: bytes, fmt: str | None) -> bytes:
    """Audio from the A100 as WAV bytes, whatever it was sent as."""
    if not fmt or fmt == "wav":
        return audio
    import io

    import soundfile

    samples, rate = soundfile.read(io.BytesIO(audio))
    out = io.BytesIO()
    soundfile.write(out, samples, rate, format="WAV", subtype="PCM_16")
    return out.getvalue()


def request_json(
    path: str,
    body: dict | None = None,
    *,
    url: str | None = None,
    key: str | None = None,
    timeout: float = TIMEOUT_SECONDS,
    headers: dict | None = None,
) -> dict:
    root = base_url(url)
    if not root:
        raise A100Unavailable("ยังไม่ได้ตั้งค่า UDTH_A100_URL")
    token = api_key(key)
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = urllib.request.Request(
        f"{root}{path}",
        data=data,
        method="POST" if body is not None else "GET",
    )
    req.add_header("Content-Type", "application/json")
    for name, value in (headers or {}).items():
        req.add_header(name, value)
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")[:300]
        if exc.code in (401, 403):
            raise TtsError(
                f"A100 Voice Server ไม่รับ API key (HTTP {exc.code}) — ตรวจ UDTH_A100_KEY ใน .env"
            ) from exc
        if exc.code == 428:
            raise KeyError("missing_ref") from exc
        if exc.code in (502, 503, 504, 530):
            raise A100Unavailable(f"A100 Voice Server ไม่ตอบ (HTTP {exc.code})") from exc
        raise TtsError(f"A100 Voice Server ตอบ HTTP {exc.code}: {detail}") from exc
    except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as exc:
        raise A100Unavailable(f"ติดต่อ A100 Voice Server ไม่ได้: {exc}") from exc


def synthesize_remote(
    *,
    engine: str,
    voice: str,
    text: str,
    output_path: Path,
    source_lang: str | None = None,
    instruct: str | None = None,
    ref_path: Path | None = None,
    ref_text: str | None = None,
    url: str | None = None,
    key: str | None = None,
    timeout: float = TIMEOUT_SECONDS,
) -> dict:
    """Synthesize speech on the remote A100 server and write WAV atomically."""
    root = base_url(url)
    payload: dict = {
        "engine": engine,
        "voice": voice,
        "text": text,
    }
    if source_lang:
        payload["source_lang"] = source_lang
    if instruct:
        payload["instruct"] = instruct

    ref_id = None
    if ref_path is not None:
        if not ref_path.is_file():
            raise TtsError(f"ไม่พบไฟล์เสียงตัวอย่าง {ref_path} — ตรวจ UDTH_VOICE_REF ใน .env")
        ref_id = reference_identity(ref_path, ref_text)
        payload["ref_id"] = ref_id
        if ref_text:
            payload["ref_text"] = ref_text
        with _state_lock:
            needs_upload = (root, ref_id) not in _uploaded_refs
        if needs_upload:
            payload["ref_audio_b64"] = base64.b64encode(ref_path.read_bytes()).decode("ascii")

    extra = {"X-Audio-Format": COMPRESSED_FORMAT} if _can_decode_compressed() else None
    with _gate.turn(priority.get()):
        try:
            reply = request_json("/v1/tts", payload, url=url, key=key, timeout=timeout, headers=extra)
        except KeyError:
            # Server restarted and lost its in-memory reference cache; resend audio bytes once.
            if ref_path is None or ref_id is None:
                raise A100Unavailable("A100 ขอไฟล์เสียงตัวอย่างซ้ำแต่ไม่ได้ระบุไฟล์")
            payload["ref_audio_b64"] = base64.b64encode(ref_path.read_bytes()).decode("ascii")
            reply = request_json("/v1/tts", payload, url=url, key=key, timeout=timeout, headers=extra)

    if ref_id is not None:
        with _state_lock:
            _uploaded_refs.add((root, ref_id))

    audio_b64 = reply.get("audio_b64")
    if not isinstance(audio_b64, str) or not audio_b64:
        raise TtsError(f"A100 Voice Server ไม่ได้ส่งข้อมูลเสียงกลับมาสำหรับ {voice}")

    try:
        wav_bytes = _to_wav(base64.b64decode(audio_b64), reply.get("format"))
    except Exception as exc:  # a corrupt clip must not be cached as if it were good
        raise TtsError(f"อ่านเสียงจาก A100 ไม่ได้: {exc}") from exc
    output_path.parent.mkdir(parents=True, exist_ok=True)
    partial = output_path.with_name(output_path.name + ".part")
    try:
        partial.write_bytes(wav_bytes)
        partial.replace(output_path)
    finally:
        if partial.is_file():
            try:
                partial.unlink()
            except OSError:
                pass

    if ref_id and reply.get("ref_text") and not ref_text:
        kept = output_path.parent / f"ref-{ref_id}.txt"
        try:
            kept.write_text(str(reply["ref_text"]).strip(), encoding="utf-8")
        except OSError:
            pass

    result: dict = {"file": output_path.name, "cached": False}
    spoken = (reply.get("text") or "").strip()
    if spoken:
        result["text"] = spoken
    return result
